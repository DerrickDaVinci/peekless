//! Cheap clipboard change detection for the background guard.
//!
//! We never read clipboard *contents* on a timer. We poll the OS change
//! counter (NSPasteboard.changeCount / GetClipboardSequenceNumber), which is a
//! single integer, and only read and scan when it moves.
//!
//! Password managers mark what they copy as concealed; we respect that and
//! never look at those entries.

use std::sync::atomic::{AtomicIsize, Ordering};

static OWN_WRITE: AtomicIsize = AtomicIsize::new(isize::MIN);

/// Call right after Peekless itself writes to the clipboard, so the guard
/// does not react to its own output.
pub fn mark_own_write() {
    if let Some(c) = change_count() {
        OWN_WRITE.store(c, Ordering::SeqCst);
    }
}

pub fn is_own_write(count: isize) -> bool {
    OWN_WRITE.load(Ordering::SeqCst) == count
}

#[cfg(target_os = "macos")]
mod imp {
    use objc2_app_kit::NSPasteboard;

    // nspasteboard.org conventions, honoured by 1Password, Bitwarden,
    // KeePassXC, Keychain Access and most clipboard managers.
    const SKIP: [&str; 4] = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"];

    pub fn change_count() -> Option<isize> {
        Some(NSPasteboard::generalPasteboard().changeCount())
    }

    pub fn is_concealed() -> bool {
        let Some(types) = NSPasteboard::generalPasteboard().types() else { return false };
        types.iter().any(|t| SKIP.contains(&t.to_string().as_str()))
    }
}

#[cfg(target_os = "windows")]
mod imp {
    use windows::core::w;
    use windows::Win32::System::DataExchange::{GetClipboardSequenceNumber, IsClipboardFormatAvailable, RegisterClipboardFormatW};

    pub fn change_count() -> Option<isize> {
        Some(unsafe { GetClipboardSequenceNumber() } as isize)
    }

    pub fn is_concealed() -> bool {
        // The Windows equivalent of the concealed marker.
        unsafe {
            let f = RegisterClipboardFormatW(w!("ExcludeClipboardContentFromMonitorProcessing"));
            f != 0 && IsClipboardFormatAvailable(f).is_ok()
        }
    }
}

#[cfg(not(any(target_os = "macos", target_os = "windows")))]
mod imp {
    pub fn change_count() -> Option<isize> {
        None
    }
    pub fn is_concealed() -> bool {
        false
    }
}

pub use imp::{change_count, is_concealed};
